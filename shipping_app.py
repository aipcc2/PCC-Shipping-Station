    c = ws.cell(row=r, column=1, value="Phone: (770) 638 8658   Fax: (770) 638 8659")
    c.font = normal; c.alignment = center_al
    r += 1

    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=3)
