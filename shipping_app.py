        lines=[l.strip() for l in v.replace('\r','').split('\n') if l.strip()]
        if len(lines)>1:
            added=0; dupes=0
            for sn in lines:
                if sn in self._sn: dupes+=1
                else: self._sn.append(sn); added+=1
            self._ref(); self._lb.see("end"); self._var.set(""); self._entry.focus_set()
            if dupes: messagebox.showinfo("Paste result",f"Added {added} serial(s).\n{dupes} duplicate(s) skipped.",parent=self)
            return
        if v in self._sn: messagebox.showwarning("Duplicate",f"{v} already in list.",parent=self); self._var.set(""); self._entry.focus_set(); return
        self._sn.append(v); self._ref(); self._lb.see("end"); self._var.set(""); self._entry.focus_set()
