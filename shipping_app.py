def search_wo_folder(division,wo):
    """Search by WO number first, then by engineering number if no WO match."""
    root=Path(PRODUCTION_ROOTS[division]); wp=wo[:5] if len(wo)>=5 else wo
    exact,full_p,short_p=[],[],[]
    # ── Pass 1: Search by WO folder name ──
    try:
        for pd in root.rglob("Production Data"):
            if not pd.is_dir(): continue
            for e in pd.iterdir():
                if not e.is_dir(): continue
                n=e.name
                if n==wo: exact.append(e)
                elif n.startswith(wo) and len(n)>len(wo) and n[len(wo)] in ("."," ","_"): full_p.append(e)
                elif n.startswith(wp) and e not in exact: short_p.append(e)
    except Exception: pass
    if exact: return exact
    if full_p: return full_p
    if short_p: return short_p

    # ── Pass 2: Search by engineering number ──
    # Normalize input: strip LF/lf suffix for comparison
    eng_input=wo.strip()
    eng_norm=eng_input.upper()
    if eng_norm.endswith("LF"): eng_norm=eng_norm[:-2]

    eng_matches=[]
    try:
        for pd in root.rglob("Production Data"):
            if not pd.is_dir(): continue
            jf=pd.parent  # job folder e.g. "15102203 Water Draw Box [3156LF Rev. - Rev. -]"
            jname=jf.name
            bp=jname.find("[")
            if bp<0: continue
            inside=jname[bp+1:]
            cl=inside.find("]")
            if cl>0: inside=inside[:cl]
            # Extract eng number (tokens before "Rev")
            parts=inside.strip().split()
            eng_parts=[]
            for p in parts:
                if p.lower().startswith("rev"): break
                eng_parts.append(p)
            folder_eng=" ".join(eng_parts).strip().upper()
            # Also strip LF from folder eng for comparison
            folder_eng_norm=folder_eng
            if folder_eng_norm.endswith("LF"): folder_eng_norm=folder_eng_norm[:-2]

            if eng_norm==folder_eng_norm or eng_norm==folder_eng:
                # Found matching job folder — collect all WO folders inside Production Data
                for e in pd.iterdir():
                    if e.is_dir() and e not in eng_matches:
                        eng_matches.append(e)
    except Exception: pass
    return eng_matches

def _clean_customer_name(name):
    """
    Strip leading numeric folder prefixes like '10 Honeywell' -> 'Honeywell'.
    Only strips when digits are followed by a separator (space, dash, dot, underscore),
    so embedded digits in real customer names are preserved.

    Examples:
      '10 Honeywell'       -> 'Honeywell'
      '0001 Acme Corp'     -> 'Acme Corp'
      '25-Boeing'          -> 'Boeing'
      '7. Lockheed Martin' -> 'Lockheed Martin'
      'Liber8now'          -> 'Liber8now'   (no separator after 8 -> kept intact)
      '3M'                 -> '3M'          (no separator -> kept intact)
      'Honeywell'          -> 'Honeywell'   (no leading digits -> unchanged)
    """
    if not name: return name
    import re
    m = re.match(r'^\d+[\s\-_.]+(.+)$', name)
    return m.group(1).strip() if m else name

